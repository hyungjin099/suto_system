-- ==========================================================================
-- 주문 자동화 시스템 통합 스키마 + 시드 데이터
--
-- 한 번 실행하면 모든 테이블이 생성되고 기본 데이터까지 들어갑니다.
-- 기존 데이터가 있다면 전부 삭제되므로 운영 환경 적용 시 백업 필수.
-- ==========================================================================

SET FOREIGN_KEY_CHECKS = 0;

DROP TABLE IF EXISTS ORDER_AUDIT;
DROP TABLE IF EXISTS ADMIN_USER;
DROP TABLE IF EXISTS CLIENT_FABRIC_ALIAS;
DROP TABLE IF EXISTS ORDER_ITEM;
DROP TABLE IF EXISTS ORDER_INFO;
DROP TABLE IF EXISTS PRODUCT_INFO;
DROP TABLE IF EXISTS CLIENT_INFO;
DROP TABLE IF EXISTS SUPPLIER_INFO;

SET FOREIGN_KEY_CHECKS = 1;


-- ==========================================================================
-- 1. 매입처 (원단을 매입하는 회사. PROD_INFO.MANUFACTURER 드롭다운 옵션)
-- ==========================================================================
CREATE TABLE SUPPLIER_INFO (
    SUP_NUM  INT AUTO_INCREMENT,
    SUP_NAME VARCHAR(100) NOT NULL UNIQUE,
    CONSTRAINT PK_SUPPLIER_INFO PRIMARY KEY (SUP_NUM)
);


-- ==========================================================================
-- 2. 거래처 (주문 페이지를 사용하는 고객사)
-- ==========================================================================
CREATE TABLE CLIENT_INFO (
    CLI_NUM           INT AUTO_INCREMENT,
    CLI_CODE          VARCHAR(20)  NOT NULL UNIQUE,        -- 거래처코드 (주문 URL 식별자)
    CLI_COMP_NAME     VARCHAR(100) NOT NULL,               -- 거래처명
    CLI_CEO_NAME      VARCHAR(50),                         -- 대표자명
    CLI_TEL           VARCHAR(20),                         -- 전화
    CLI_FAX           VARCHAR(20),                         -- Fax
    CLI_MANAGER_NAME  VARCHAR(50),                         -- 담당자명
    CLI_MANAGER_TEL   VARCHAR(20),                         -- 담당자 모바일
    CLI_EMAIL         VARCHAR(100),                        -- 담당자 Email
    CLI_ADDRESS       VARCHAR(200),                        -- 주소 (기본 + 상세 결합)
    CLI_USE_TYPE      VARCHAR(20) DEFAULT 'YES',           -- 사용구분 ('YES' / 'NO')
    CLI_PASSWORD      VARCHAR(100) DEFAULT '1234',         -- 주문 페이지 접근 비밀번호 (최초 '1234')
    JOIN_DATE         DATETIME DEFAULT SYSDATE(),
    CONSTRAINT PK_CLIENT_INFO PRIMARY KEY (CLI_NUM)
);


-- ==========================================================================
-- 3. 원단 마스터
-- ==========================================================================
CREATE TABLE PRODUCT_INFO (
    PROD_NUM     INT AUTO_INCREMENT,
    PROD_CODE    VARCHAR(30)  NOT NULL,                    -- 제품코드 (중복 허용)
    PROD_NAME    VARCHAR(100) NOT NULL,                    -- 제품명 (중복 허용)
    PROD_PRICE   INT          NULL,                        -- 단가 (NULL 허용)
    MANUFACTURER VARCHAR(50),                              -- 매입처명 (SUPPLIER_INFO.SUP_NAME)
    PROD_STATUS  VARCHAR(10) DEFAULT '사용',                -- 사용여부 ('사용' / '미사용')
    REG_DATE     DATETIME DEFAULT SYSDATE(),
    CONSTRAINT PK_PRODUCT_INFO PRIMARY KEY (PROD_NUM)
);


-- ==========================================================================
-- 4. 거래처별 원단 별칭 (고객사가 부르는 이름 + 적용단가)
-- ==========================================================================
CREATE TABLE CLIENT_FABRIC_ALIAS (
    ALIAS_NUM        INT AUTO_INCREMENT,
    CLI_NUM          INT          NOT NULL,
    PROD_NUM         INT          NOT NULL,
    CLIENT_FAB_NAME  VARCHAR(100) NOT NULL,                -- 고객사가 부르는 별칭
    CLIENT_FAB_PRICE INT          NULL,                    -- 고객사 적용단가
    REG_DATE         DATETIME DEFAULT SYSDATE(),
    CONSTRAINT PK_CLIENT_FABRIC_ALIAS PRIMARY KEY (ALIAS_NUM),
    CONSTRAINT UQ_CLI_PROD            UNIQUE (CLI_NUM, PROD_NUM),
    CONSTRAINT UQ_CLI_NAME            UNIQUE (CLI_NUM, CLIENT_FAB_NAME),
    CONSTRAINT FK_ALIAS_CLIENT        FOREIGN KEY (CLI_NUM)  REFERENCES CLIENT_INFO(CLI_NUM),
    CONSTRAINT FK_ALIAS_PROD          FOREIGN KEY (PROD_NUM) REFERENCES PRODUCT_INFO(PROD_NUM)
);


-- ==========================================================================
-- 5. 주문 헤더
-- ==========================================================================
CREATE TABLE ORDER_INFO (
    ORDER_NUM  INT AUTO_INCREMENT,
    CLI_CODE   VARCHAR(20) NOT NULL,                       -- FK CLIENT_INFO.CLI_CODE
    ORDER_ID   VARCHAR(30) NOT NULL UNIQUE,                -- 'ORD-XXXXXX'
    STATUS          VARCHAR(20) DEFAULT 'PENDING',                  -- 시트 전송 상태 ('PENDING'/'OK'/'FAILED')
    WORKFLOW_STATUS VARCHAR(20) DEFAULT 'RECEIVED',                  -- 비즈니스 상태 (RECEIVED → IN_PROGRESS → SHIPPED → DONE / CANCELLED)
    ORDER_DATE      DATETIME    DEFAULT SYSDATE(),
    CONSTRAINT PK_ORDER_INFO  PRIMARY KEY (ORDER_NUM),
    CONSTRAINT FK_ORDER_CLIENT FOREIGN KEY (CLI_CODE) REFERENCES CLIENT_INFO(CLI_CODE)
);


-- ==========================================================================
-- 6. 주문 품목 (한 주문에 여러 원단)
-- ==========================================================================
CREATE TABLE ORDER_ITEM (
    ITEM_NUM      INT AUTO_INCREMENT,
    ORDER_NUM     INT NOT NULL,
    PRODUCT       VARCHAR(50),                             -- 제품코드 (스냅샷)
    PRODUCT_LABEL VARCHAR(100),                            -- 제품명 (스냅샷)
    WIDTH         INT,
    LENGTH        INT,
    ROLLS         INT,
    DESTINATION   VARCHAR(500),                            -- 납품처
    NOTE          TEXT,                                    -- 비고
    DELIVERY_DATE VARCHAR(20),                             -- 납품예정일 (override, NULL이면 발주일 기준 자동계산)
    UNIT_PRICE    INT NULL,                                -- 주문 당시 단가 (가격 스냅샷)
    ALIAS_NAME    VARCHAR(100) NULL,                       -- 주문 당시 거래처 별칭 (스냅샷)
    CONSTRAINT PK_ORDER_ITEM PRIMARY KEY (ITEM_NUM),
    CONSTRAINT FK_ITEM_ORDER FOREIGN KEY (ORDER_NUM) REFERENCES ORDER_INFO(ORDER_NUM)
);


-- ==========================================================================
-- 7. 관리자 계정
-- ==========================================================================
CREATE TABLE ADMIN_USER (
    ADMIN_NUM               INT AUTO_INCREMENT,
    USERNAME                VARCHAR(50)  NOT NULL UNIQUE,
    PASSWORD                VARCHAR(100) NOT NULL,                  -- BCrypt 해시
    DISPLAY_NAME            VARCHAR(50),
    PASSWORD_RESET_REQUIRED CHAR(1)   NOT NULL DEFAULT 'Y',         -- Y: 최초 로그인 시 비번 변경 강제
    USE_YN                  CHAR(1)   NOT NULL DEFAULT 'Y',         -- N: 비활성(로그인 차단). 세션 만료 후 재로그인 시점부터 차단
    REG_DATE                DATETIME  DEFAULT SYSDATE(),
    CONSTRAINT PK_ADMIN_USER PRIMARY KEY (ADMIN_NUM)
);
-- 기본 관리자(admin / admin1234)는 백엔드 시작 시 AdminUserService.ensureDefaultAdmin()에서 자동 생성됨.
-- USERNAME='admin' 계정은 최고 관리자로, 다른 관리자 계정을 추가/비활성화할 수 있으며 본인은 비활성화되지 않는다.
-- 기존 운영 DB 마이그레이션:
--   ALTER TABLE ADMIN_USER
--     ADD COLUMN PASSWORD_RESET_REQUIRED CHAR(1) NOT NULL DEFAULT 'Y' AFTER DISPLAY_NAME,
--     ADD COLUMN USE_YN                  CHAR(1) NOT NULL DEFAULT 'Y' AFTER PASSWORD_RESET_REQUIRED;


-- ==========================================================================
-- 8. 주문 감사 로그 (누가 언제 무엇을 변경했는지 기록)
-- ==========================================================================
CREATE TABLE ORDER_AUDIT (
    AUDIT_NUM   BIGINT AUTO_INCREMENT,
    ORDER_NUM   INT NOT NULL,
    ITEM_NUM    INT NULL,                                  -- 품목 단위 변경이면 채움
    ACTION      VARCHAR(30) NOT NULL,                      -- CREATE / UPDATE / DELETE / STATUS_CHANGE / WORKFLOW_CHANGE
    ACTOR       VARCHAR(50),                               -- 관리자 username, 고객 주문은 'CUSTOMER'
    BEFORE_JSON TEXT NULL,
    AFTER_JSON  TEXT NULL,
    MEMO        VARCHAR(200) NULL,                         -- 사람이 보는 요약
    AT          DATETIME DEFAULT SYSDATE(),
    CONSTRAINT PK_ORDER_AUDIT PRIMARY KEY (AUDIT_NUM)
);
CREATE INDEX IX_ORDER_AUDIT_ORDER ON ORDER_AUDIT(ORDER_NUM);


